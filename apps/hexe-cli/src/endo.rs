//! `endo-survey <Resources-dir> [--out SURVEY.md]` and `open <file.ens|.nmc|.nmb|.nma> [--out scene.json]`.
//! Clean-room from data: the survey is the vocabulary of the sample corpus, nothing else is consulted.
use hexe_geo::endorphin::{self, Document, Vocab};
use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::{Path, PathBuf};

/// Largest Endorphin file read (hostile input is the default).
const MAX_FILE_BYTES: u64 = 256 << 20;
const EXTS: [&str; 8] = ["ens", "nmc", "nmb", "nma", "nmp", "nmw", "nmm", "nme"];

fn walk(dir: &Path, out: &mut Vec<PathBuf>, depth: usize) {
    if depth > 16 {
        return;
    }
    let Ok(rd) = std::fs::read_dir(dir) else { return };
    for e in rd.flatten() {
        let p = e.path();
        if p.is_dir() {
            walk(&p, out, depth + 1);
        } else {
            out.push(p);
        }
    }
}

fn ext_of(p: &Path) -> String {
    p.extension().and_then(|e| e.to_str()).unwrap_or("").to_ascii_lowercase()
}

fn read_capped(p: &Path) -> Result<Vec<u8>, String> {
    let meta = std::fs::metadata(p).map_err(|e| format!("{}: {e}", p.display()))?;
    if meta.len() > MAX_FILE_BYTES {
        return Err(format!("{}: larger than {MAX_FILE_BYTES} bytes", p.display()));
    }
    std::fs::read(p).map_err(|e| format!("{}: {e}", p.display()))
}

fn attr_cell(t: &endorphin::TagStat) -> String {
    let mut cells = Vec::new();
    for (a, n) in &t.attrs {
        if let Some(rest) = a.strip_prefix('b')
            && t.attrs.contains_key(rest)
        {
            continue; // listed as the `(+hex)` twin of its decimal sibling
        }
        let twin = t.attrs.contains_key(&format!("b{a}"));
        cells.push(format!("{a}{}\u{d7}{n}", if twin { "(+hex)" } else { "" }));
    }
    if cells.is_empty() { "-".into() } else { cells.join(" ") }
}

fn child_cell(t: &endorphin::TagStat) -> String {
    let mut v: Vec<_> = t.child_tags.iter().collect();
    v.sort_by(|a, b| b.1.cmp(a.1).then(a.0.cmp(b.0)));
    let total = v.len();
    let mut s: Vec<String> = v.into_iter().take(10).map(|(k, n)| format!("{k}\u{d7}{n}")).collect();
    if total > 10 {
        s.push(format!("+{} more", total - 10));
    }
    if s.is_empty() { "-".into() } else { s.join(" ") }
}

struct ExtSurvey {
    files: u64,
    ok: u64,
    roots: BTreeMap<String, u64>,
    vocab: Vocab,
    elements: u64,
    failures: Vec<String>,
    bytes_xml: u64,
}

/// Parse every Endorphin file below `root`; render the vocabulary report.
pub fn survey(root: &Path) -> Result<String, String> {
    let mut files = Vec::new();
    walk(root, &mut files, 0);
    files.sort();
    let mut per: BTreeMap<String, ExtSurvey> = BTreeMap::new();
    let mut other: BTreeMap<String, u64> = BTreeMap::new();
    for f in &files {
        let ext = ext_of(f);
        if !EXTS.contains(&ext.as_str()) {
            *other.entry(ext).or_insert(0) += 1;
            continue;
        }
        let s = per.entry(ext).or_insert_with(|| ExtSurvey {
            files: 0,
            ok: 0,
            roots: BTreeMap::new(),
            vocab: Vocab::default(),
            elements: 0,
            failures: Vec::new(),
            bytes_xml: 0,
        });
        s.files += 1;
        let rel = f.strip_prefix(root).unwrap_or(f).display().to_string();
        let tree = read_capped(f).and_then(|b| {
            let xml = if b.first() == Some(&0x78) { endorphin::inflate(&b).map_err(|e| e.to_string())? } else { b };
            s.bytes_xml += xml.len() as u64;
            endorphin::read_tree(&xml).map_err(|e| e.to_string())
        });
        match tree {
            Ok(n) => {
                s.ok += 1;
                *s.roots.entry(n.tag.clone()).or_insert(0) += 1;
                s.elements += n.count() as u64;
                s.vocab.add(&n);
            }
            Err(e) => s.failures.push(format!("{rel}: {e}")),
        }
    }
    if per.is_empty() {
        return Err(format!("{}: no Endorphin files (.ens .nmc .nmb .nma ...) found", root.display()));
    }
    let mut o = String::new();
    let _ = writeln!(o, "# Endorphin 2.x file format \u{2014} vocabulary survey\n");
    let _ = writeln!(
        o,
        "Clean-room, from data: this is the element/attribute vocabulary measured off the shipped sample files of one Endorphin 2.5.2 install (`Resources/`, {} files walked). No vendor code, binary or documentation was consulted. Generated by `hexe-cli endo-survey`; reader = `crates/geo/src/endorphin.rs`.\n",
        files.len()
    );
    let _ = writeln!(
        o,
        "## Container\n\n- zlib stream (`78 01`) -> UTF-8 XML, one root element. Same container for every extension.\n- Floats: attribute pairs `x=\"0.95\"` (decimal, lossy) + `bx=\"3f735159\"` (hex IEEE-754 single, exact). The reader prefers the hex twin (`(+hex)` below). Some attributes are hex-only (`bparam0`, `brestitution`, ...).\n- `TransformMatrix` = `Vi Vj Vk` basis columns + `Vp` translation, each `x y z`. Joint matrices are parent-local; MetaBody matrices are joint-local.\n- `.nmb` roots are `<cc>` with opaque text-encoded blobs in attributes (`vw`, `lo`, ...): NOT decoded (unknown); only `RefNames` and attribute names are read.\n"
    );
    let _ = writeln!(o, "{}", include_str!("../../../oracle/endorphin/SCENE_POSE.md"));
    let _ = writeln!(
        o,
        "## Files\n\n| ext | files | parsed | root elements | elements | inflated MB |\n|---|---|---|---|---|---|"
    );
    let (mut tot_f, mut tot_ok) = (0, 0);
    let mut all = Vocab::default();
    for (e, s) in &per {
        let roots: Vec<String> = s.roots.iter().map(|(k, n)| format!("`{k}`\u{d7}{n}")).collect();
        let _ = writeln!(
            o,
            "| .{e} | {} | {}/{} | {} | {} | {:.1} |",
            s.files,
            s.ok,
            s.files,
            roots.join(" "),
            s.elements,
            s.bytes_xml as f64 / 1_048_576.0
        );
        tot_f += s.files;
        tot_ok += s.ok;
        for (t, st) in &s.vocab.tags {
            let a = all.tags.entry(t.clone()).or_default();
            a.elements += st.elements;
            a.files += st.files;
            for (k, n) in &st.attrs {
                *a.attrs.entry(k.clone()).or_insert(0) += n;
            }
            for (k, n) in &st.child_tags {
                *a.child_tags.entry(k.clone()).or_insert(0) += n;
            }
        }
    }
    let pairs: usize = all.tags.values().map(|t| t.attrs.len()).sum();
    let _ = writeln!(
        o,
        "\n**Total: {tot_ok}/{tot_f} parsed. Vocabulary: {} distinct element names, {pairs} distinct (element, attribute) pairs.**\n",
        all.tags.len()
    );
    if !other.is_empty() {
        let v: Vec<String> = other.iter().map(|(k, n)| format!(".{k}\u{d7}{n}")).collect();
        let _ = writeln!(o, "Other files in the tree (not Endorphin documents, not parsed): {}.\n", v.join(" "));
    }
    for (e, s) in &per {
        for f in &s.failures {
            let _ = writeln!(o, "- FAILED .{e}: {f}");
        }
    }
    for (e, s) in &per {
        let _ = writeln!(
            o,
            "## .{e} vocabulary ({} elements names)\n\n| element | count | files | attributes (count) | children (count) |\n|---|---|---|---|---|",
            s.vocab.tags.len()
        );
        for (t, st) in &s.vocab.tags {
            let _ = writeln!(o, "| `{t}` | {} | {} | {} | {} |", st.elements, st.files, attr_cell(st), child_cell(st));
        }
        let _ = writeln!(o);
    }
    Ok(o)
}

pub fn survey_cmd(args: &[String]) -> Result<String, String> {
    let mut dir = None;
    let mut out = None;
    let mut it = args.iter();
    while let Some(a) = it.next() {
        match a.as_str() {
            "--out" | "-o" => out = Some(it.next().ok_or("endo-survey: --out needs a path")?.clone()),
            f if f.starts_with('-') => return Err(format!("endo-survey: unknown option `{f}`")),
            p if dir.is_none() => dir = Some(p.to_string()),
            x => return Err(format!("endo-survey: unexpected argument `{x}`")),
        }
    }
    let dir = dir.ok_or("usage: hexe-cli endo-survey <Resources-dir> [--out SURVEY.md]")?;
    let md = survey(Path::new(&dir))?;
    match out {
        Some(p) => {
            std::fs::write(&p, &md).map_err(|e| format!("{p}: {e}"))?;
            let head = md.lines().find(|l| l.starts_with("**Total")).unwrap_or("");
            Ok(format!("survey -> {p}\n{head}\n"))
        }
        None => Ok(md),
    }
}

/// `.ens .nmc .nmb .nma` (case-insensitive).
pub fn is_endo(path: &str) -> bool {
    let l = path.to_ascii_lowercase();
    [".ens", ".nmc", ".nmb", ".nma"].iter().any(|e| l.ends_with(e))
}

/// One-node graph (`file` SOP -> the absolute Endorphin path, display on it): the file SOP reads Endorphin via `read_any`.
pub fn scene_json(file: &str) -> Result<String, String> {
    let abs = std::fs::canonicalize(file).map_err(|e| format!("{file}: {e}"))?;
    Ok(format!(
        "{{\"nodes\":[{{\"name\":\"endo\",\"type\":\"file\",\"params\":{{\"file\":{:?}}}}}],\"display\":\"endo\"}}\n",
        abs.display().to_string()
    ))
}

/// Graph `open` writes for a scene (.ens): `file` SOP -> `endosim` SOP (passive-ragdoll physics, scrubbed by the timeline `$F`),
/// display on the sim. Everything else (.nmc/.nmb/.nma) stays the one-node rest-pose `scene_json`.
pub fn scene_json_sim(file: &str) -> Result<String, String> {
    let abs = std::fs::canonicalize(file).map_err(|e| format!("{file}: {e}"))?;
    Ok(format!(
        "{{\"nodes\":[{{\"name\":\"endo\",\"type\":\"file\",\"params\":{{\"file\":{:?}}}}},{{\"name\":\"sim\",\"type\":\"endosim\",\"params\":{{}}}}],\"edges\":[[\"endo\",0,\"sim\",0]],\"display\":\"sim\"}}\n",
        abs.display().to_string()
    ))
}

/// `open <file> [--out scene.json] [--geo out.geo]`: read an Endorphin file, write the hexe graph (and optionally the geometry).
pub fn open_cmd(args: &[String]) -> Result<String, String> {
    let (mut file, mut out, mut geo) = (None, None, None);
    let mut it = args.iter();
    while let Some(a) = it.next() {
        match a.as_str() {
            "--out" | "-o" => out = Some(it.next().ok_or("open: --out needs a path")?.clone()),
            "--geo" => geo = Some(it.next().ok_or("open: --geo needs a path")?.clone()),
            f if f.starts_with('-') => return Err(format!("open: unknown option `{f}`")),
            p if file.is_none() => file = Some(p.to_string()),
            x => return Err(format!("open: unexpected argument `{x}`")),
        }
    }
    let file = file.ok_or("usage: hexe-cli open <file.ens|.nmc|.nmb|.nma> [--out scene.json] [--geo out.geo]")?;
    if !is_endo(&file) {
        return Err(format!("open: `{file}` is not .ens/.nmc/.nmb/.nma"));
    }
    let bytes = read_capped(Path::new(&file))?;
    let doc = endorphin::read_endorphin(&bytes).map_err(|e| format!("{file}: {e}"))?;
    let d = hexe_geo::endorphin_geo::document_detail(&doc);
    let stem = Path::new(&file).file_stem().and_then(|s| s.to_str()).unwrap_or("endorphin").replace(' ', "_");
    let out = out.unwrap_or_else(|| format!("{stem}.hexe.json"));
    std::fs::write(&out, if matches!(doc, Document::Scene(_)) { scene_json_sim(&file)? } else { scene_json(&file)? })
        .map_err(|e| format!("{out}: {e}"))?;
    if let Some(g) = &geo {
        hexe_geo::write_any(g, &d).map_err(|e| format!("{g}: {e}"))?;
    }
    let (kind, chars, joints, bodies, behaviours) = match &doc {
        Document::Scene(s) => {
            let cs: Vec<_> = s.characters.iter().chain(s.environment.iter()).collect();
            (
                "scene",
                cs.len(),
                cs.iter().map(|c| c.joints.len()).sum(),
                cs.iter().map(|c| c.bodies.len()).sum(),
                s.behaviours.len(),
            )
        }
        Document::Character(c) => ("character", 1, c.joints.len(), c.bodies.len(), 0),
        Document::Behaviour(_) => ("behaviour", 0, 0, 0, 1),
        Document::Pose(_) => ("pose", 0, 0, 0, 0),
        Document::Unknown(_) => ("unknown", 0, 0, 0, 0),
    };
    let (lo, hi) = d.bbox();
    Ok(format!(
        "opened {kind} {file}: {chars} characters, {joints} joints, {bodies} bodies, {behaviours} behaviours -> {} points, {} prims, bbox {lo:?}..{hi:?}; graph {out}{}\n",
        d.point_count,
        d.prim_count(),
        geo.map(|g| format!(", geo {g}")).unwrap_or_default()
    ))
}

//! `cargo xtask sops [--check]`: generate `docs/SOPS.md` (SOP coverage + parameter schema) from the live registry.
//! Sources: `crates/sop/src/builtins/mod.rs` `r.register("<type>", ...)` lines (must equal `hexe_sop::registry()`),
//! each SOP's `spec()` param schema + input ports, `parity/features.toml` (row whose `commands` hold the type,
//! `sop-<type>` first), `examples/*.json` (dedicated = `examples/<type>.json` uses it, else first scene using it).
//! `--check` (what `cargo xtask ci` runs) fails when the committed file differs: regenerate with `cargo xtask sops`.
use crate::{Res, root};
use hexe_graph::ParamValue;
use std::collections::BTreeSet;
use std::fmt::Write as _;
use std::path::Path;

/// Register types named in `builtins/mod.rs`, in file order (commented-out lines are skipped).
pub fn registered(mod_rs: &str) -> Vec<String> {
    mod_rs
        .lines()
        .filter_map(|l| {
            let rest = l.trim_start().strip_prefix("r.register(\"")?;
            Some(rest.split('"').next()?.to_string())
        })
        .collect()
}

fn fmt_default(v: &ParamValue, menu: &[(String, String)]) -> String {
    match v {
        ParamValue::F(x) => format!("{x}"),
        ParamValue::I(x) => format!("{x}"),
        ParamValue::B(x) => format!("{x}"),
        ParamValue::V3(x) => format!("[{}, {}, {}]", x[0], x[1], x[2]),
        ParamValue::S(s) if s.is_empty() => "\"\"".to_string(),
        ParamValue::S(s) => format!("{s:?}"),
        ParamValue::Menu(i) => menu.get(*i as usize).map_or_else(|| format!("{i}"), |(t, _)| t.clone()),
    }
}

fn kind(v: &ParamValue) -> &'static str {
    match v {
        ParamValue::F(_) => "float",
        ParamValue::I(_) => "int",
        ParamValue::B(_) => "bool",
        ParamValue::V3(_) => "vec3",
        ParamValue::S(_) => "string",
        ParamValue::Menu(_) => "menu",
    }
}

fn esc(s: &str) -> String {
    s.replace('|', "\\|").replace('\n', " ")
}

/// Every `"type": "<x>"` string value in a scene JSON.
fn types_in(v: &serde_json::Value, out: &mut BTreeSet<String>) {
    match v {
        serde_json::Value::Object(m) => {
            if let Some(serde_json::Value::String(t)) = m.get("type") {
                out.insert(t.clone());
            }
            m.values().for_each(|c| types_in(c, out));
        }
        serde_json::Value::Array(a) => a.iter().for_each(|c| types_in(c, out)),
        _ => {}
    }
}

fn examples(root: &Path) -> Result<Vec<(String, BTreeSet<String>)>, String> {
    let dir = root.join("examples");
    let mut files: Vec<_> = std::fs::read_dir(&dir)
        .map_err(|e| format!("read {}: {e}", dir.display()))?
        .filter_map(|e| e.ok().map(|e| e.path()))
        .filter(|p| p.extension().is_some_and(|x| x == "json"))
        .collect();
    files.sort();
    let mut out = Vec::new();
    for p in files {
        let Some(name) = p.file_name().and_then(|n| n.to_str()).map(str::to_string) else { continue };
        let text = std::fs::read_to_string(&p).map_err(|e| format!("read {}: {e}", p.display()))?;
        let Ok(v) = serde_json::from_str::<serde_json::Value>(&text) else { continue };
        let mut set = BTreeSet::new();
        types_in(&v, &mut set);
        out.push((name, set));
    }
    Ok(out)
}

/// Render `docs/SOPS.md` for `root`.
pub fn render(root: &Path) -> Result<String, String> {
    let mod_rs = std::fs::read_to_string(root.join("crates/sop/src/builtins/mod.rs"))
        .map_err(|e| format!("read builtins/mod.rs: {e}"))?;
    let lines = registered(&mod_rs);
    let reg = hexe_sop::registry();
    let mut want: Vec<String> = lines.clone();
    want.sort();
    let have: Vec<String> = reg.type_names().iter().map(|s| (*s).to_string()).collect();
    if want != have {
        return Err(format!(
            "mod.rs has {} register lines but the registry holds {} types (duplicate / generated registration?)",
            want.len(),
            have.len()
        ));
    }
    let ledger = crate::parity::load(root)?;
    let ex = examples(root)?;
    let mut md = String::new();
    let n = want.len();
    let _ = writeln!(md, "# SOP coverage\n");
    let _ = writeln!(
        md,
        "GENERATED by `cargo xtask sops` (drift = `cargo xtask ci` failure; never hand-edit). Src: `crates/sop/src/builtins/mod.rs` → {n} `r.register(...)` (type list; `registry.rs` = container only)."
    );
    let _ =
        writeln!(md, "Parity: first `parity/features.toml` row whose `commands` hold the type (`sop-<x>` preferred).");
    let _ = writeln!(
        md,
        "Example: `examples/<x>.json` = dedicated · `via <f>.json` = SOP only inside multi-SOP scene `<f>`."
    );
    let _ = writeln!(
        md,
        "Render: `hexe-tauri examples/<f>.json --render <png> --size 480x300` (proof PNGs not committed; not generated here).\n"
    );
    let _ = writeln!(md, "| SOP | in | params | parity | example |\n|---|---|---|---|---|");
    let (mut covered, mut dedicated, mut shipped, mut partial, mut planned, mut norow) = (0, 0, 0, 0, 0, 0);
    for t in &want {
        let node = reg.create(t).ok_or_else(|| format!("registry cannot construct `{t}`"))?;
        let nparams = reg.specs(t).map_or(0, |s| s.len());
        let exact = format!("sop-{t}");
        let row = ledger.feature.iter().find(|f| f.id == exact).or_else(|| {
            ledger
                .feature
                .iter()
                .find(|f| f.commands.iter().any(|c| c == t) && (f.id.starts_with("sop-") || f.id.starts_with("rop-")))
        });
        let parity = match row {
            Some(f) => {
                match f.status.as_str() {
                    "shipped" => shipped += 1,
                    "partial" => partial += 1,
                    _ => planned += 1,
                }
                format!("{} ({})", f.status, f.id)
            }
            None => {
                norow += 1;
                "no row".to_string()
            }
        };
        let own = format!("{t}.json");
        let example = if let Some((f, _)) = ex.iter().find(|(f, s)| *f == own && s.contains(t)) {
            covered += 1;
            dedicated += 1;
            format!("`{f}`")
        } else if let Some((f, _)) = ex.iter().find(|(_, s)| s.contains(t)) {
            covered += 1;
            format!("via `{f}`")
        } else {
            "none".to_string()
        };
        let _ = writeln!(md, "| [{t}](#{t}) | {} | {nparams} | {parity} | {example} |", node.inputs().len());
    }
    let _ = writeln!(
        md,
        "\nTotals: {n} SOPs · {covered} with an example ({dedicated} dedicated + {} via) · parity {shipped} shipped / {partial} partial / {planned} planned / {norow} no-row · {} params in total.",
        covered - dedicated,
        want.iter().map(|t| reg.specs(t).map_or(0, |s| s.len())).sum::<usize>()
    );
    let _ = writeln!(md, "Gaps: {} SOP w/o example.\n", n - covered);
    let _ = writeln!(md, "## Parameters\n");
    for t in &want {
        let node = reg.create(t).ok_or_else(|| format!("registry cannot construct `{t}`"))?;
        let ins: Vec<&str> = node.inputs().iter().map(|i| i.name).collect();
        let _ = writeln!(md, "### {t}\n");
        let _ = writeln!(md, "Inputs: {}.\n", if ins.is_empty() { "none".to_string() } else { ins.join(", ") });
        let specs = reg.specs(t).unwrap_or_default();
        if specs.is_empty() {
            let _ = writeln!(md, "No parameters.\n");
            continue;
        }
        let _ = writeln!(md, "| param | label | type | default | range / menu |\n|---|---|---|---|---|");
        for p in &specs {
            let extra = if !p.menu.is_empty() {
                p.menu.iter().map(|(tok, _)| tok.as_str()).collect::<Vec<_>>().join(" · ")
            } else if !p.choices.is_empty() {
                p.choices.join(" · ")
            } else if let Some((lo, hi)) = p.range {
                format!("{lo} … {hi}")
            } else {
                String::new()
            };
            let _ = writeln!(
                md,
                "| `{}` | {} | {} | `{}` | {} |",
                p.name,
                esc(&p.label),
                kind(&p.default),
                esc(&fmt_default(&p.default, &p.menu)),
                esc(&extra)
            );
        }
        md.push('\n');
    }
    while md.ends_with("\n\n") {
        md.pop();
    }
    Ok(md)
}

pub fn run(args: &[String]) -> Res {
    let root = root();
    let md = render(&root)?;
    let path = root.join("docs/SOPS.md");
    if args.iter().any(|a| a == "--check") {
        let cur = std::fs::read_to_string(&path).unwrap_or_default();
        if cur != md {
            return Err("docs/SOPS.md is stale: run `cargo xtask sops` and commit".into());
        }
        println!("sops: docs/SOPS.md up to date ({} SOPs)", registered_count(&root));
        return Ok(());
    }
    std::fs::write(&path, &md).map_err(|e| format!("write {}: {e}", path.display()))?;
    println!("sops: wrote docs/SOPS.md ({} SOPs)", registered_count(&root));
    Ok(())
}

fn registered_count(root: &Path) -> usize {
    std::fs::read_to_string(root.join("crates/sop/src/builtins/mod.rs")).map_or(0, |t| registered(&t).len())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn register_lines_are_counted_and_comments_skipped() {
        let src = "fn b(r: &mut R) {\n    r.register(\"null\", a::spec, a::new);\n//\n    // r.register(\"x\", x::spec, x::new);\n    r.register(\"box\", b::spec, b::new);\n}";
        assert_eq!(registered(src), vec!["null", "box"]);
    }

    #[test]
    fn committed_doc_matches_the_registry() {
        let root = root();
        let md = render(&root).expect("render");
        let n = registered_count(&root);
        assert!(md.contains(&format!("→ {n} `r.register(...)`")));
        assert_eq!(md.matches("\n### ").count(), n, "one parameter section per SOP");
        assert_eq!(
            std::fs::read_to_string(root.join("docs/SOPS.md")).unwrap_or_default(),
            md,
            "run `cargo xtask sops`"
        );
    }

    #[test]
    fn defaults_format_by_kind() {
        assert_eq!(fmt_default(&ParamValue::V3([0.0, 1.5, 2.0]), &[]), "[0, 1.5, 2]");
        assert_eq!(fmt_default(&ParamValue::Menu(1), &[("a".into(), "A".into()), ("b".into(), "B".into())]), "b");
        assert_eq!(fmt_default(&ParamValue::S(String::new()), &[]), "\"\"");
    }
}
